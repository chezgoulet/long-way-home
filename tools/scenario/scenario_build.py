#!/usr/bin/env python3
"""Compile a scenario manifest's declaration contract to the flat file the ship loader reads.

    python3 tools/scenario/scenario_build.py SCENARIO-DIR [--out DIR]
    python3 tools/scenario/scenario_build.py --fields          # the field names, one per line
    python3 tools/scenario/scenario_build.py --flat SCENARIO-DIR  # print the flat text

The manifest (`scenario.json`) is validated by `tools/validator/declarations.py` -- the same schema
the validator uses, so the builder and the validator cannot disagree about what a field is. The flat
`maps/<name>.scenario` is what `module/ship/scenario_core.cpp` parses: line-oriented, `#` comments,
quoted text fields. A manifest whose declaration fails validation is not built.

This is the bridge between the authored contract and the game, the way `tools/crewgen/crewgen.py
build` is for the crew section. It writes no game state; it renders declared fields.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "validator"))
import declarations  # noqa: E402


def q(text):
    """A quoted flat-format string; the loader's tokenizer reads one token for it."""
    return '"' + str(text).replace('"', "'") + '"'


def num(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def render(man):
    name = man["name"]
    lines = [f"# Generated by tools/scenario from {name}/scenario.json. Edit the manifest, not this file."]
    lines.append(f"scenario {name}")
    if "canon_root" in man:
        lines.append(f"canon-root {q(man['canon_root'])}")
    for c in man.get("breeding_conditions", []):
        lines.append(f"condition {c['state']} {c['op']} {num(c['value'])}")
    for entry in man.get("systems", []):
        if isinstance(entry, str):
            lines.append(f"system read {q(entry)}")
        elif entry.get("off"):
            lines.append(f"system off {q(entry['id'])}")
        else:
            lines.append(f"system stress {q(entry['id'])} {num(entry.get('stress', 0))}")
    for post in man.get("staff", []):
        lines.append(f"staff {q(post)}")
    cost = man.get("cost", {})
    for branch in ("answer", "ignore"):
        if branch in cost:
            lines.append(f"cost-{branch} {q(cost[branch].get('text', ''))}")
            for e in cost[branch].get("effects", []):
                lines.append(_effect(branch, e))
    for e in man.get("residue", []):
        if isinstance(e, str):
            lines.append(f"residue {q(e)}")
        else:
            lines.append(_effect("residue", e))
    for v in man.get("visibility", []):
        v = str(v)
        kind, _, val = v.partition(":")
        if kind in ("station", "system", "deck"):
            lines.append(f"visibility {kind} {q(val)}")
        else:
            lines.append(f"visibility station {q(v)}")  # a bare station name
    for beat in man.get("warmth", []):
        lines.append(f"warmth {q(beat)}")
    for p in man.get("positions", []):
        lines.append(f"position {q(p['post'])}")
        for info in p.get("information", []):
            lines.append(f"position-info {q(p['post'])} {q(info)}")
        for a in p.get("authority", []):
            lines.append(f"position-authority {q(p['post'])} {q(a)}")
        for r in p.get("responsible_for", []):
            lines.append(f"position-responsible {q(p['post'])} {q(r)}")
        if p.get("decision"):
            lines.append(f"position-decision {q(p['post'])} {q(p['decision'])}")
    if "decision" in man:
        lines.append(f"decision {q(man['decision'].get('question', ''))}")
        for i, o in enumerate(man["decision"].get("options", [])):
            lines.append(f"option {q(o['label'])}")
            for e in o.get("cost", []):
                lines.append(_effect(f"option:{i}", e))
    for ln in man.get("lines", []):
        lines.append(f"line {q(ln['to'])} {ln['delivery']} {q(ln['text'])}")
    return "\n".join(lines) + "\n"


def _effect(branch, e):
    args = " ".join(f"{k}={q(v)}" for k, v in e.items() if k != "effect")
    return f"effect {branch} {e['effect']} {args}".rstrip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scenario", nargs="?")
    ap.add_argument("--out", default=None)
    ap.add_argument("--fields", action="store_true", help="print the declaration field names and exit")
    ap.add_argument("--flat", action="store_true", help="print the flat declaration to stdout")
    a = ap.parse_args()

    if a.fields:
        for f in declarations.FIELDS:
            print(f)
        return 0
    if not a.scenario:
        ap.error("a scenario directory is required (or --fields)")

    path = os.path.join(a.scenario, "scenario.json")
    try:
        man = json.load(open(path, encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"error: {path}: {e}", file=sys.stderr)
        return 1

    findings = []
    declarations.check(man, findings)
    if findings:
        for f in findings:
            print(f"error: {f.code} {f.where}: {f.detail}", file=sys.stderr)
        print(f"error: the manifest does not satisfy the declaration contract; nothing written", file=sys.stderr)
        return 1

    flat = render(man)
    if a.flat:
        sys.stdout.write(flat)
        return 0
    out_dir = a.out if a.out else os.path.join(a.scenario, "build")
    dest = os.path.join(out_dir, "maps", man["name"] + ".scenario")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as f:
        f.write(flat)
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
